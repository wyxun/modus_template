"""Generate the FLOAT and integer-only Q15 quarter-wave tables for mfoc."""
from pathlib import Path
import math


def render():
    values = [math.sin(i * math.pi / 1024) for i in range(513)]
    lines = ['/* Generated by mfoc/tools/gen_sin_table.py. */',
             '#if defined(MFOC_NUMERIC_FLOAT)',
             'static const float s_sin_quarter[513] = {']
    for start in range(0, 513, 4):
        lines.append('    ' + ', '.join(f'{v:.9f}f' for v in
                     values[start:start + 4]) + ',')
    lines += ['};', '#else',
              'static const int32_t s_sin_quarter[513] = {']
    fixed = [int(v * 32768 + 0.5) for v in values]
    for start in range(0, 513, 10):
        lines.append('    ' + ', '.join(str(v) for v in
                     fixed[start:start + 10]) + ',')
    lines += ['};', '#endif', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    target = Path(__file__).resolve().parents[1] / 'base/src/mfoc_sin_table.inc'
    target.write_text(render(), encoding='utf-8')
